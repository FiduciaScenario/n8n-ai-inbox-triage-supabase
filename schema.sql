-- Idempotent PostgreSQL schema for AI Inbound Lead Triage (Supabase)
CREATE TABLE IF NOT EXISTS public.inbound_leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    message_hash TEXT NOT NULL UNIQUE, -- Prevents duplicate webhook processing
    sender_email TEXT NOT NULL,
    company_domain TEXT,
    is_business_email BOOLEAN DEFAULT FALSE,
    clean_message TEXT,
    intent TEXT CHECK (intent IN ('sales_lead', 'support', 'spam')),
    lead_score INTEGER CHECK (lead_score >= 0 AND lead_score <= 100),
    urgency TEXT CHECK (urgency IN ('high', 'medium', 'low')),
    detected_pain_point TEXT,
    draft_reply TEXT
);

CREATE INDEX IF NOT EXISTS idx_inbound_leads_score ON public.inbound_leads (lead_score DESC);
